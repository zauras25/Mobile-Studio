create unique index if not exists customer_orders_tracking_code_key
  on public.customer_orders (tracking_code);

do $$
declare
  v_order record;
  v_candidate integer;
  v_tracking_code text;
begin
  for v_order in
    select id
    from public.customer_orders
    where tracking_code is null
    order by created_at, id
  loop
    v_candidate := mod(v_order.id, 1000000)::integer;
    loop
      v_tracking_code := lpad(v_candidate::text, 6, '0');
      exit when not exists (
        select 1
        from public.customer_orders
        where tracking_code = v_tracking_code
      );
      v_candidate := (v_candidate + 1) % 1000000;
      if v_candidate = mod(v_order.id, 1000000)::integer then
        raise exception 'No six-digit customer order tracking codes remain.';
      end if;
    end loop;

    update public.customer_orders
    set tracking_code = v_tracking_code
    where id = v_order.id;
  end loop;
end;
$$;

