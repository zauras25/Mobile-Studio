create or replace function public.record_customer_order_status()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.customer_order_status_history (order_id, status)
    values (new.id, new.status);
  elsif new.status is distinct from old.status then
    if new.status = 'Cancelled' and old.status <> 'Cancelled' then
      update public.products product
      set stock = product.stock + item.quantity
      from public.customer_order_items item
      where item.order_id = new.id
        and item.product_id = product.id;
    elsif old.status = 'Cancelled' and new.status <> 'Cancelled' then
      if exists (
        select 1
        from public.customer_order_items item
        join public.products product on product.id = item.product_id
        where item.order_id = new.id
          and product.stock < item.quantity
      ) then
        raise exception 'Not enough stock to reopen this cancelled order.';
      end if;
      update public.products product
      set stock = product.stock - item.quantity
      from public.customer_order_items item
      where item.order_id = new.id
        and item.product_id = product.id;
    end if;
    insert into public.customer_order_status_history (order_id, status)
    values (new.id, new.status);
  end if;
  return new;
end;
$$;

