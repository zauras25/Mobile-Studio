      from public.customer_order_items items
      where items.order_id = orders.id
    ), '[]'::jsonb),
    'subtotal', orders.subtotal,
    'delivery', orders.delivery,
    'total', orders.total,
    'status', orders.status,
    'paymentStatus', orders.payment_status,
    'createdAt', orders.created_at,
    'statusHistory', coalesce((
      select jsonb_agg(jsonb_build_object('status', history.status, 'createdAt', history.created_at) order by history.created_at)
      from public.customer_order_status_history history
      where history.order_id = orders.id
    ), '[]'::jsonb)
  )
  from public.customer_orders orders
  where orders.id = p_order_id
    and regexp_replace(orders.phone, '[^0-9]', '', 'g') = p_phone_digits
$$;

create or replace function public.track_customer_order(
  p_order_number text,
  p_phone text
)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.customer_order_json(
    orders.id,
    regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g')
  )
  from public.customer_orders orders
  where (
        upper(orders.order_number) = upper(trim(coalesce(p_order_number, '')))
        or orders.tracking_code = trim(coalesce(p_order_number, ''))
      )
    and regexp_replace(orders.phone, '[^0-9]', '', 'g') =
        regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g')
$$;

