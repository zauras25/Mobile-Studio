create or replace function public.create_customer_order(
  p_name text,
  p_phone text,
  p_address text,
  p_city text,
  p_items jsonb,
  p_preferred_courier text default 'store_choice',
  p_fulfillment_method text default 'delivery',
  p_area text default '',
  p_expected_delivery numeric default null,
  p_payment_method text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order_id bigint;
  v_order_number text;
  v_tracking_code text;
  v_candidate integer;
  v_attempt integer;
  v_code_found boolean;
  v_order public.customer_orders%rowtype;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_subtotal numeric(12, 2) := 0;
  v_delivery numeric(12, 2);
  v_total numeric(12, 2);
  v_settings jsonb;
  v_charge numeric(12, 2);
  v_threshold numeric(12, 2);
  v_zone jsonb;
begin
  if char_length(trim(coalesce(p_name, ''))) not between 3 and 120 then
    raise exception 'Enter a valid customer name.';
  end if;
  if regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g') !~ '^03[0-9]{9}$' then
    raise exception 'Enter a valid Pakistani mobile number.';
  end if;
  if coalesce(p_fulfillment_method, '') not in ('delivery', 'store_pickup') then
    raise exception 'Choose delivery or store pickup.';
  end if;
  if coalesce(p_payment_method, '') not in ('JazzCash', 'EasyPaisa', 'Bank transfer') then
    raise exception 'Choose a valid payment method.';
  end if;
  if p_fulfillment_method = 'store_pickup'
     and (p_expected_delivery is null or p_expected_delivery < 0) then
    raise exception 'Review the delivery charge before submitting your order.';
  end if;
  if p_fulfillment_method = 'delivery' then
    if char_length(trim(coalesce(p_address, ''))) not between 10 and 500 then
      raise exception 'Enter a complete delivery address.';
    end if;
    if char_length(trim(coalesce(p_city, ''))) not between 2 and 120 then
      raise exception 'Enter a valid city.';
    end if;
    if char_length(trim(coalesce(p_area, ''))) not between 2 and 120 then
      raise exception 'Choose a valid delivery area.';
    end if;
    if lower(trim(p_city)) = 'lahore' then
      if p_expected_delivery is null or p_expected_delivery < 0 then
        raise exception 'Review the Lahore local delivery charge before submitting your order.';
      end if;
      if coalesce(p_preferred_courier, '') <> 'store_choice' then
        raise exception 'Lahore orders use local delivery; courier selection is not available.';
      end if;
    else
      if p_expected_delivery is not null then
        raise exception 'Nationwide courier delivery charges are confirmed by the store.';
      end if;
      if coalesce(p_preferred_courier, '') = 'store_choice' then
        raise exception 'Choose a courier or postal service for delivery outside Lahore.';
      end if;
    end if;
  end if;
  if coalesce(p_preferred_courier, '') not in
     ('store_choice', 'postex', 'tcs', 'leopards', 'mnp', 'pakistan_post') then
    raise exception 'Choose a valid preferred delivery service.';
  end if;
  if p_items is null or jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'Your cart contents are invalid.';
  end if;
  if jsonb_array_length(p_items) not between 1 and 50 then
    raise exception 'Your cart must contain between 1 and 50 products.';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_items) as requested(value)
    group by requested.value->>'product_id'
    having count(*) > 1
  ) then
    raise exception 'The cart contains a repeated product. Refresh your cart and try again.';
  end if;

  v_order_number := 'UMP-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12));
  perform pg_advisory_xact_lock(hashtext('customer-order-tracking-code'));
  v_candidate := floor(random() * 1000000)::integer;
  v_code_found := false;
  for v_attempt in 1..1000000
  loop
    v_tracking_code := lpad(v_candidate::text, 6, '0');
    if not exists (
      select 1
      from public.customer_orders
      where tracking_code = v_tracking_code
    ) then
      v_code_found := true;
      exit;
    end if;
    v_candidate := (v_candidate + 1) % 1000000;
  end loop;
  if not v_code_found then
    raise exception 'No six-digit customer order tracking codes remain.';
  end if;

  insert into public.customer_orders (
    order_number, tracking_code, customer_name, phone, address, city, delivery_area,
    fulfillment_method, preferred_courier, payment_method, subtotal, delivery, total
  )
  values (v_order_number, v_tracking_code, trim(p_name), trim(p_phone),
          case when p_fulfillment_method = 'store_pickup' then 'Store pickup - address to be confirmed' else trim(p_address) end,
          case when p_fulfillment_method = 'store_pickup' then 'Store pickup' else trim(p_city) end,
          case when p_fulfillment_method = 'store_pickup' then 'Store pickup' else trim(p_area) end,
          p_fulfillment_method,
          case when p_fulfillment_method = 'store_pickup' then 'store_choice' else p_preferred_courier end,
          p_payment_method,
          0, null, null)
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item->>'product_id', '') !~ '^[0-9]+$'
       or coalesce(v_item->>'quantity', '') !~ '^[0-9]+$' then
      raise exception 'The cart contains an invalid product or quantity.';
    end if;
    v_quantity := (v_item->>'quantity')::integer;
    if v_quantity not between 1 and 99 then
      raise exception 'Product quantities must be between 1 and 99.';
    end if;

    select product.* into v_product
    from public.products product
    join public.categories category on category.name = product.category
    where product.id = (v_item->>'product_id')::bigint
      and product.is_published
      and category.is_enabled
    for update of product;
    if not found then
      raise exception 'A product in your cart is no longer available.';
    end if;
    if v_product.stock < v_quantity then
      raise exception 'Not enough stock is available for %.', v_product.name;
    end if;

    v_subtotal := v_subtotal + (v_product.price * v_quantity);
    insert into public.customer_order_items (
      order_id, product_id, product_name, product_slug, product_image, unit_price, quantity
    )
    values (
      v_order_id, v_product.id, v_product.name, v_product.slug,
      v_product.image, v_product.price, v_quantity
    );
    update public.products
    set stock = stock - v_quantity,
        updated_at = now()
    where id = v_product.id;
  end loop;

  if p_fulfillment_method = 'store_pickup' then
    v_delivery := 0;
    v_total := v_subtotal;
  elsif lower(trim(p_city)) <> 'lahore' then
    v_delivery := null;
    v_total := null;
  else
    select setting_value into v_settings
    from public.site_settings where setting_key = 'delivery';
    if coalesce(v_settings->>'details_verified', 'false') is distinct from 'true'
       or jsonb_typeof(v_settings->'zones') is distinct from 'array' then
      raise exception 'Location-based delivery rates are not configured. Choose store pickup or contact the store.';
    end if;
    select zone.value into v_zone
    from jsonb_array_elements(v_settings->'zones') as zone(value)
    where lower(trim(coalesce(zone.value->>'city', ''))) = lower(trim(p_city))
      and lower(trim(coalesce(zone.value->>'area', ''))) = lower(trim(p_area))
    limit 1;
    if v_zone is null and lower(trim(p_city)) = 'lahore' then
      select zone.value into v_zone
      from jsonb_array_elements(v_settings->'zones') as zone(value)
      where lower(trim(coalesce(zone.value->>'city', ''))) = 'lahore'
        and lower(trim(coalesce(zone.value->>'area', ''))) = 'lahore (all localities)'
      limit 1;
    end if;
    if v_zone is null then
      raise exception 'No confirmed delivery charge is configured for this area. Choose store pickup or contact the store.';
    end if;
    begin
      v_charge := (v_zone->>'charge')::numeric;
      v_threshold := nullif(v_zone->>'free_threshold', '')::numeric;
    exception when invalid_text_representation then
      raise exception 'The delivery charge for this area is invalid. Contact the store.';
    end;
    if v_charge is null or v_charge < 0
       or (v_threshold is not null and v_threshold < 0) then
      raise exception 'The delivery charge for this area is invalid. Contact the store.';
    end if;
    v_delivery := case
      when v_threshold is not null and v_subtotal > 0 and v_subtotal >= v_threshold then 0
      else v_charge
    end;
    v_total := v_subtotal + v_delivery;
  end if;
  if v_delivery is not null
     and abs(v_delivery - p_expected_delivery) > 0.01 then
    raise exception 'The delivery rate changed while you were checking out. Refresh checkout and review the updated charge.';
  end if;

  update public.customer_orders
  set order_number = v_order_number,
      subtotal = v_subtotal,
      delivery = v_delivery,
      total = v_total,
      updated_at = now()
  where id = v_order_id
  returning * into v_order;

  return public.customer_order_json(v_order.id, regexp_replace(v_order.phone, '[^0-9]', '', 'g'));
end;
$$;

create or replace function public.customer_order_json(
  p_order_id bigint,
  p_phone_digits text
)
